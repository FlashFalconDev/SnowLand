const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),Module=require('node:module'),vm=require('node:vm')
const root=path.resolve(__dirname,'../snowland-frontend'),req=Module.createRequire(path.join(root,'package.json')),ts=req('typescript')
const context=vm.createContext({exports:{}})
vm.runInContext(ts.transpileModule(fs.readFileSync(path.join(root,'src/utils/siteLocale.ts'),'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText,context)
const {resolveSiteLocale,readSiteLanguagePreference,translateSiteText}=context.exports
assert.equal(resolveSiteLocale('auto',['ja-JP','en-US']),'ja')
assert.equal(resolveSiteLocale('auto',['en-GB','zh-TW']),'en')
assert.equal(resolveSiteLocale('auto',['fr-FR','ja']),'ja')
assert.equal(resolveSiteLocale('auto',['zh-CN','en']),'zh-Hant')
assert.equal(resolveSiteLocale('ja',['en-US']),'ja','Manual choice overrides browser language')
assert.equal(resolveSiteLocale('auto',[]),'zh-Hant')
assert.equal(resolveSiteLocale('malformed',[null,'JA-jp']),'ja')
assert.equal(readSiteLanguagePreference({getItem:()=>{throw Error('blocked')}}),'auto')
assert.equal(readSiteLanguagePreference({getItem:()=>'<script>'}),'auto')
assert.equal(readSiteLanguagePreference({getItem:()=> 'en'}),'en')
assert.equal(translateSiteText('ja','預約課程'),'レッスンを予約')
assert.equal(translateSiteText('en','會員專區'),'Member area')
assert.equal(translateSiteText('ja','電子郵件'),'メールアドレス')
assert.equal(translateSiteText('en','會員登入'),'Sign in')
assert.equal(translateSiteText('zh-Hant','會員專區'),'會員專區')
assert.equal(translateSiteText('en','QA 客人自訂雪場'),'QA 客人自訂雪場','Never translate names or arbitrary CMS/member content')
const React=req('react'),{renderToStaticMarkup}=req('react-dom/server'),router=req('react-router-dom')
for(const [saved,languages,expected] of [['auto',['ja-JP'],'レッスンを予約'],['en',['ja-JP'],'Book a lesson'],['zh-Hant',['en'],'預約課程']]){
  const provider=vm.createContext({exports:{},navigator:{languages},window:{localStorage:{getItem:()=>saved}},require:name=>name==='react'?React:name==='react-router-dom'?router:context.exports})
  vm.runInContext(ts.transpileModule(fs.readFileSync(path.join(root,'src/contexts/SiteLocale.jsx'),'utf8'),{compilerOptions:{jsx:ts.JsxEmit.React,module:ts.ModuleKind.CommonJS,esModuleInterop:true}}).outputText,provider)
  const Probe=()=>React.createElement('p',null,provider.exports.useSiteLocale().t('預約課程'))
  assert.ok(renderToStaticMarkup(React.createElement(router.StaticRouter,{location:'/snowland/membership'},React.createElement(provider.exports.SiteLocaleProvider,null,React.createElement(Probe)))).includes(expected),'Real React provider must supply the selected language to child controls')
}
console.log('PASS site language: browser priority, manual override, invalid/storage fallback, real navigation translation and untouched custom content')
